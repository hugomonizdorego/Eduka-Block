TRANSLATIONS = {"en": EN, "tet": TET, "pt_PT": PT_PT, "pt_BR": PT_BR, "id": ID}
FALLBACKS = {"pt_BR": "pt_PT"}


def tr(key: str, language: str = DEFAULT_LANGUAGE, **values) -> str:
    template = TRANSLATIONS.get(language, {}).get(key)
    if template is None and language in FALLBACKS:
        template = TRANSLATIONS[FALLBACKS[language]].get(key)
    if template is None:
        template = EN.get(key, key)
    values.setdefault("version", APP_VERSION)
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def load_language(path: Path) -> str:
    try:
        value = json.loads(path.read_text(encoding="utf-8")).get("language", DEFAULT_LANGUAGE)
    except (OSError, UnicodeError, json.JSONDecodeError, AttributeError):
        value = DEFAULT_LANGUAGE
    return value if value in LANGUAGES else DEFAULT_LANGUAGE


def save_language(path: Path, language: str) -> None:
    if language not in LANGUAGES:
        language = DEFAULT_LANGUAGE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"language": language}, indent=2) + "\n", encoding="utf-8")
